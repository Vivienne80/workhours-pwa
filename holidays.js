export const WEEKDAY_LABELS = ['월','화','수','목','금','토','일'];

export function dateKey(d) {
  return `${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`;
}

export function isWeekend(d) {
  return d.getDay() === 0 || d.getDay() === 6;
}

export function isPublicHoliday(d) {
  return !!KOREAN_HOLIDAYS[dateKey(d)];
}

export function isHoliday(d) {
  return isWeekend(d) || isPublicHoliday(d);
}

export function weekdayLabel(d) {
  return WEEKDAY_LABELS[d.getDay() === 0 ? 6 : d.getDay() - 1];
}
